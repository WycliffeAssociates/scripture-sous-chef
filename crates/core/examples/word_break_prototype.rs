//! THROWAWAY prototype — NOT part of the crate's shipped surface.
//!
//! Follow-up to `word_break_survey.rs` / `documentation/calibration/
//! 2026-07-17-word-break-fast-path-survey.md`. That survey argued a
//! word-break fast path could reuse existing `Class` bits plus direct char/
//! range matching for the small enumerable categories, mirroring
//! `crate::grapheme`'s hand-rolled fast path + `COMPLEX` fallback (ADR 0021).
//! This program actually BUILDS that walker (minimal, correctness-only, no
//! performance tuning) and runs it against:
//!
//!   1. The official UCD `WordBreakTest.txt` conformance suite (same ÷/×
//!      format `grapheme.rs`'s `conforms_to_graphemebreaktest` parses).
//!   2. A real-corpus differential against `unicode-segmentation`'s own
//!      `unicode_word_indices()` (WA-subset or the full 1,504-corpus fleet).
//!
//! ## Two promoted bits (Part 2 of the follow-up — now real production code)
//!
//! The first version of this prototype approximated every category via
//! either an existing `Class` bit or a `WordBreakProperty.txt` runtime
//! lookup. Two of those lookups have since been promoted into real `Class`
//! bits (`crates/core/src/charclass.rs`, generated by
//! `xtask/src/gen_charclass_table.rs` from the same UCD ranges) — the last 2
//! genuinely free bits (30, 31; bit 6 stays reserved for a future `clinging`
//! flag), both spent here per the steer to use a free bit when a real case
//! justifies it:
//!
//!   - **`WB_EXTEND`** = `Word_Break` ∈ {Extend, ZWJ}. Deliberately narrower
//!     than `Class::is_extender()` (GCB Extend|SpacingMark|ZWJ, correct for
//!     grapheme clustering, where all three glue to the base) — some
//!     `GCB=SpacingMark` scalars are genuinely `Word_Break=Other` (e.g.
//!     U+0EB3 LAO VOWEL SIGN AM), so `is_extender()` wrongly absorbed them
//!     into the preceding word ("ນ້ຳ" (water) split into two word-break
//!     segments per real UAX #29, but `is_extender()`-based absorption fused
//!     it into one — the bug that drove the ~2.07% pre-fix corpus mismatch
//!     rate; see `build_atoms`'s doc comment).
//!   - **`WB_SEP`** = `Word_Break` ∈ {MidLetter, MidNum, MidNumLet,
//!     ExtendNumLet, Single_Quote, Double_Quote} (42 codepoints total) — a
//!     hot-loop candidate-separator fast-reject; `wb_sep_category` below
//!     does the literal char match to disambiguate which of the six on the
//!     rare hit, mirroring how `QUOTE_CHARS` is hardcoded rather than looked
//!     up from a UCD file at runtime.
//!
//! `Format` (58 UCD codepoints) wasn't promoted — still a
//! `WordBreakProperty.txt` lookup, same as `Hebrew_Letter`/`Katakana`/
//! `WSegSpace`/the `ALetter`/`Numeric` residual patches below (none of those
//! were in scope for the bit promotion).
//!
//! ## Design (mirrors `grapheme.rs`'s fast-path/COMPLEX-fallback shape)
//!
//! Any scalar with `Class::is_complex()` set (Hangul jamo pieces, Regional
//! Indicator, Extended_Pictographic/emoji, Prepend, Control, CR, LF — the
//! exact same bit `grapheme.rs` uses to punt to `unicode-segmentation`)
//! defers the WHOLE input string to the crate's own `split_word_bounds`/
//! `unicode_word_indices`. Scripture has ~zero emoji/flags/Hangul (per
//! `grapheme.rs`'s own module doc), so this fallback should be rare, not
//! load-bearing — exactly like the grapheme segmenter's `COMPLEX` bucket.
//!
//! For everything else, this hand-rolls a subset of UAX #29 (WB3d-WB13b;
//! WB1/2/3/3a/3b/3c/15/16 are subsumed by the `is_complex` fallback since
//! CR/LF/Newline/Regional_Indicator/Extended_Pictographic are all
//! `is_complex()==true` — verified directly against `GraphemeBreakProperty.txt`
//! before writing this):
//!
//!   - `ALetter`  ≈ `class_of(c).is_alphabetic()` MINUS scripts the survey
//!     found diverge (Thai/Lao/Khmer/Myanmar/Han/Hiragana — scriptio
//!     continua scripts UAX #29 deliberately excludes from `ALetter`), PLUS
//!     a tiny exact-match patch for the residual the corpus differential
//!     found (`wb == Wb::ALetter`; e.g. U+00B8 CEDILLA, GC=Sk not alphabetic
//!     but genuinely `Word_Break=ALetter`).
//!   - `Numeric`  ≈ `class_of(c).is_decimal_digit()` PLUS the same kind of
//!     exact-match patch (`wb == Wb::Numeric`; e.g. U+066B ARABIC DECIMAL
//!     SEPARATOR, GC=Po not a digit but genuinely `Word_Break=Numeric`).
//!   - `Extend`/`ZWJ` (the bulk of the WB4 "ignore" set) ← `Class::is_wb_extend()`
//!     (the promoted bit); `Format` stays a small `wb == Wb::Format` lookup.
//!   - `MidLetter`/`MidNum`/`MidNumLet`/`ExtendNumLet`/`Single_Quote`/
//!     `Double_Quote` ← `Class::is_wb_sep()` (the promoted bit) plus
//!     `wb_sep_category`'s literal match.
//!   - `Hebrew_Letter`, `Katakana`, `WSegSpace` — still parsed directly from
//!     the committed `WordBreakProperty.txt` (small enumerable categories
//!     out of scope for the bit promotion; exact UCD lookup costs nothing
//!     for them either).
//!
//! Run: cargo run -p ssc-core --release --example word_break_prototype

