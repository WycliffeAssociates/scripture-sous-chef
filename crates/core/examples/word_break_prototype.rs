// ---------------------------------------------------------------------
// UCD Word_Break parsing (same shape as word_break_survey.rs — duplicated,
// not shared, since both are independent throwaway examples).
// ---------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Wb {
    ALetter,
    CR,
    DoubleQuote,
    Extend,
    ExtendNumLet,
    Format,
    HebrewLetter,
    Katakana,
    LF,
    MidLetter,
    MidNum,
    MidNumLet,
    Newline,
    Numeric,
    RegionalIndicator,
    SingleQuote,
    WSegSpace,
    ZWJ,
    Other,
}

fn parse_word_break(path: &Path) -> Vec<(u32, u32, Wb)> {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split(';');
        let cps = parts.next().unwrap().trim();
        let prop = parts.next().unwrap_or("").trim();
        let wb = match prop {
            "ALetter" => Wb::ALetter,
            "CR" => Wb::CR,
            "Double_Quote" => Wb::DoubleQuote,
            "Extend" => Wb::Extend,
            "ExtendNumLet" => Wb::ExtendNumLet,
            "Format" => Wb::Format,
            "Hebrew_Letter" => Wb::HebrewLetter,
            "Katakana" => Wb::Katakana,
            "LF" => Wb::LF,
            "MidLetter" => Wb::MidLetter,
            "MidNum" => Wb::MidNum,
            "MidNumLet" => Wb::MidNumLet,
            "Newline" => Wb::Newline,
            "Numeric" => Wb::Numeric,
            "Regional_Indicator" => Wb::RegionalIndicator,
            "Single_Quote" => Wb::SingleQuote,
            "WSegSpace" => Wb::WSegSpace,
            "ZWJ" => Wb::ZWJ,
            other => panic!("unexpected Word_Break value {other:?}"),
        };
        let (lo, hi) = match cps.split_once("..") {
            Some((a, b)) => (
                u32::from_str_radix(a.trim(), 16).unwrap(),
                u32::from_str_radix(b.trim(), 16).unwrap(),
            ),
            None => {
                let v = u32::from_str_radix(cps, 16).unwrap();
                (v, v)
            }
        };
        out.push((lo, hi, wb));
    }
    out.sort_unstable_by_key(|&(lo, ..)| lo);
    out
}

#[inline]
fn wb_of(ranges: &[(u32, u32, Wb)], c: char) -> Wb {
    let cp = c as u32;
    match ranges.binary_search_by(|&(lo, hi, _)| {
        if cp < lo {
            std::cmp::Ordering::Greater
        } else if cp > hi {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => ranges[i].2,
        Err(_) => Wb::Other,
    }
}

